
CREATE OR REPLACE VIEW VW_REVENUE_BY_DAY AS
SELECT
    D.FULL_DATE,
    SUM(F.AMOUNT) AS REVENUE
FROM FACT_EVENTS F
JOIN DIM_DATE D
    ON F.DATE_KEY = D.DATE_KEY
GROUP BY D.FULL_DATE;

CREATE OR REPLACE VIEW VW_TOP_CUSTOMERS AS
