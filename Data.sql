CREATE OR REPLACE VIEW VW_DAILY_KPI AS
SELECT
    D.FULL_DATE,
    COUNT(*) AS TOTAL_EVENTS,
    SUM(F.AMOUNT) AS TOTAL_REVENUE,
    AVG(F.AMOUNT) AS AVG_AMOUNT
FROM FACT_EVENTS F
JOIN DIM_DATE D
    ON F.DATE_KEY = D.DATE_KEY
GROUP BY D.FULL_DATE;

