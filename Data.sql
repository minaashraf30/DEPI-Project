    E.EVENT_TYPE,
    COUNT(*) AS EVENT_COUNT
FROM FACT_EVENTS F
JOIN DIM_EVENT_TYPE E
    ON F.EVENT_TYPE_KEY = E.EVENT_TYPE_KEY
