    C.CUSTOMER_ID,
    SUM(F.AMOUNT) AS TOTAL_SPENT
FROM FACT_EVENTS F
JOIN DIM_CUSTOMER C
    ON F.CUSTOMER_KEY = C.CUSTOMER_KEY
GROUP BY C.CUSTOMER_ID;

CREATE OR REPLACE VIEW VW_REVENUE_BY_EVENT_TYPE AS
