MERGE INTO DIM_DATE T
USING (
    SELECT DISTINCT
        TO_NUMBER(TO_CHAR(EVENT_TIMESTAMP,'YYYYMMDD')) AS DATE_KEY,
        CAST(EVENT_TIMESTAMP AS DATE) AS FULL_DATE,
        YEAR(EVENT_TIMESTAMP) AS YEAR,
        MONTH(EVENT_TIMESTAMP) AS MONTH,
        DAY(EVENT_TIMESTAMP) AS DAY,
        DAYNAME(EVENT_TIMESTAMP) AS DAY_NAME,
        WEEK(EVENT_TIMESTAMP) AS WEEK_NUM
    FROM KAFKA_EVENTS_SILVER
) S
ON T.DATE_KEY = S.DATE_KEY

WHEN NOT MATCHED THEN
INSERT (
    DATE_KEY,
    FULL_DATE,
    YEAR,
    MONTH,
    DAY,
    DAY_NAME,
    WEEK_NUM
)
VALUES (
    S.DATE_KEY,
    S.FULL_DATE,
    S.YEAR,
    S.MONTH,
    S.DAY,
    S.DAY_NAME,
    S.WEEK_NUM
);

MERGE INTO FACT_EVENTS T
USING (
    SELECT
        S.EVENT_ID,
        S.SESSION_ID,

        C.CUSTOMER_KEY,
        P.PRODUCT_KEY,
        E.EVENT_TYPE_KEY,
        D.DATE_KEY,
        CH.CHANNEL_KEY,
        DV.DEVICE_KEY,
        PM.PAYMENT_METHOD_KEY,
        OS.ORDER_STATUS_KEY,
        CUR.CURRENCY_KEY,

        S.QUANTITY,
        S.UNIT_PRICE,
        S.DISCOUNT,
        S.SUBTOTAL,
        S.AMOUNT

    FROM KAFKA_EVENTS_SILVER S

    JOIN DIM_CUSTOMER C
        ON S.CUSTOMER_ID = C.CUSTOMER_ID

    JOIN DIM_PRODUCT P
        ON S.PRODUCT_ID = P.PRODUCT_ID

    JOIN DIM_EVENT_TYPE E
        ON S.EVENT_TYPE = E.EVENT_TYPE

    JOIN DIM_DATE D
        ON CAST(S.EVENT_TIMESTAMP AS DATE) = D.FULL_DATE

    JOIN DIM_CHANNEL CH
        ON S.CHANNEL = CH.CHANNEL

    JOIN DIM_DEVICE DV
        ON S.DEVICE = DV.DEVICE

    JOIN DIM_PAYMENT_METHOD PM
        ON S.PAYMENT_METHOD = PM.PAYMENT_METHOD

    JOIN DIM_ORDER_STATUS OS
        ON S.ORDER_STATUS = OS.ORDER_STATUS

    JOIN DIM_CURRENCY CUR
        ON S.CURRENCY = CUR.CURRENCY
) S
ON T.EVENT_ID = S.EVENT_ID

WHEN NOT MATCHED THEN
INSERT (
    EVENT_ID,
    SESSION_ID,
    CUSTOMER_KEY,
    PRODUCT_KEY,
    EVENT_TYPE_KEY,
    DATE_KEY,
    CHANNEL_KEY,
    DEVICE_KEY,
    PAYMENT_METHOD_KEY,
    ORDER_STATUS_KEY,
    CURRENCY_KEY,
    QUANTITY,
    UNIT_PRICE,
    DISCOUNT,
    SUBTOTAL,
    AMOUNT
)
VALUES (
    S.EVENT_ID,
    S.SESSION_ID,
    S.CUSTOMER_KEY,
    S.PRODUCT_KEY,
    S.EVENT_TYPE_KEY,
    S.DATE_KEY,
    S.CHANNEL_KEY,
    S.DEVICE_KEY,
    S.PAYMENT_METHOD_KEY,
    S.ORDER_STATUS_KEY,
    S.CURRENCY_KEY,
    S.QUANTITY,
    S.UNIT_PRICE,
    S.DISCOUNT,
    S.SUBTOTAL,
    S.AMOUNT
);
